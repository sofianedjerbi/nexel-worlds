def trim(rows):
    """Proportional spacing: drop empty columns on both sides; returns (rows, ink width)."""
    cols = [c for c in range(5) if any(c < len(r) and r[c] == "#" for r in rows)]
    if not cols:
        return rows, 3
    lo, hi = cols[0], cols[-1]
    return [r[lo:hi + 1] for r in rows], hi - lo + 1


def glyph(rows):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        for c, ch in enumerate(row):
            if ch != "#":
                continue
            x0, x1 = c * PX, (c + 1) * PX
            y1 = (7 - r) * PX  # row 0 top = 700, baseline after row 6 = 0
            y0 = y1 - PX
            pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
    return pen.glyph()


def main():
    names = {".notdef": None, "space": " "}
    for ch in G:
        names[f"uni{ord(ch):04X}"] = ch
    order = list(names)
    fb = FontBuilder(900, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({ord(ch): n for n, ch in names.items() if ch})
    glyphs, widths = {}, {}
    for n, ch in names.items():
        if ch and ch in G:
            rows, w = trim(G[ch])
            glyphs[n], widths[n] = glyph(rows), w + 1
        else:
            glyphs[n], widths[n] = TTGlyphPen(None).glyph(), 4
    glyphs[".notdef"] = glyph(["#####", "#   #", "#   #", "#   #", "#   #", "#   #", "#####"])
    widths[".notdef"] = 6
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({n: (widths[n] * PX, 0) for n in order})
    fb.setupHorizontalHeader(ascent=800, descent=-200)
    fb.setupNameTable({"familyName": "Sprout Pixel", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=100, usWinAscent=800, usWinDescent=200)
    fb.setupPost()
    fb.save(OUT)
    print("wrote", OUT, len(G), "glyphs")


if __name__ == "__main__":
    main()
