"""Stilt: a marsh heron. Tall and thin on two long legs, a long beak; the tallest thing that is not a tree.

Animation: one step in four poses (contact, lift, pass, reach). The body sinks a pixel on contact, and the head
thrusts forward ahead of the body, as wading birds do. The peck: the neck pulls back and holds, then stabs, holds, returns.
"""
