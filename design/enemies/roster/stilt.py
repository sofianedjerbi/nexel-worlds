HEAD = range(0, 6)
BODY, SHADOW = pad(BODY, right=2), pad(SHADOW, right=2)          # room for the head to pull back
LEGS = {k: pad(v, right=2) for k, v in LEGS.items()}


def side(legs, head=0, low=False, body=BODY):
    b = nudge(body, HEAD, head) if head else body
    g = stack(b, LEGS[legs], SHADOW)
    return edit(shift(g, 0, 1, keep=7), {i - 7: r for i, r in enumerate(stack(LEGS[legs], SHADOW))} | {-7: g[-8]}) if low else g


WINDUP = nudge(nudge(BODY, HEAD, 2), range(6, 8), 1)          # the head drawn back over the body
